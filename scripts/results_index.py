#!/usr/bin/env python3
"""
An index of results/, generated from the artifacts.

WHY
---
results/ holds 27 run directories with names like B0-offline-n100-c64-rep10.
A reader arriving from the README has no way to tell which of them the headline
table rests on, which are sweep points, and which are superseded artifacts of a
bug that has since been fixed -- and three of them FAIL validity under the
current rules for exactly that reason. Left unexplained, a directory full of
runs where some fail their own checks reads as either carelessness or
cherry-picking, and a reader would be right to wonder which.

So the index is generated rather than written: every column comes out of the
run's own artifacts, and a run cannot be quietly left out of it.

    python scripts/results_index.py            # print
    python scripts/results_index.py --write    # write results/INDEX.md

No query text is read. Costs, timings and verdicts only.
"""

from __future__ import annotations

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RESULTS = os.path.join(ROOT, "results")


def _json(path: str):
    if not os.path.exists(path):
        return None
    try:
        with open(path, encoding="utf-8") as fh:
            return json.load(fh)
    except (OSError, json.JSONDecodeError):
        return None


def _lines(path: str) -> int:
    if not os.path.exists(path):
        return 0
    with open(path, encoding="utf-8") as fh:
        return sum(1 for line in fh if line.strip())


def collect(run_dir: str) -> dict | None:
    man = _json(os.path.join(run_dir, "manifest.json"))
    if not man:
        return None
    rep = _json(os.path.join(run_dir, "report.json")) or {}
    cnt = _json(os.path.join(run_dir, "counters.json")) or {}
    val = _json(os.path.join(run_dir, "validity.json")) or []
    rck = _json(os.path.join(run_dir, "validity.recheck.json")) or {}

    cost = (rep.get("cost") or {})
    thr = (rep.get("throughput") or {})
    adv = _json(os.path.join(run_dir, "advisor_eval.json")) or {}
    par = _json(os.path.join(run_dir, "parser_eval.json")) or {}

    rck_checks = rck.get("checks") or []
    added = set(rck.get("_added_after_the_runs") or [])
    # A check that could not be evaluated here is a gap, not a failure --
    # same rule check_run and recheck_runs use.
    substantive = [c for c in rck_checks
                   if not c.get("ok")
                   and c.get("verifiable", True)
                   and c.get("name") not in added]

    return {
        "dir": os.path.basename(run_dir),
        "stage": man.get("stage"),
        "n": man.get("n_queries"),
        "c": man.get("concurrency"),
        "parser": man.get("parser_kind"),
        "advisor": man.get("advisor_style"),
        "wall_s": cnt.get("wall_s"),
        "failures": _lines(os.path.join(run_dir, "failures.jsonl")),
        "usd_per_query": cost.get("cost_per_query_usd"),
        "q_per_s": thr.get("queries_per_s"),
        "ticker_acc": ((par.get("derived") or {}).get("ticker_set") or {}).get("accuracy"),
        "all_topics": adv.get("all_topics_rate"),
        "validity_then": (sum(1 for c in val if c.get("ok")), len(val)),
        "validity_now": (
            sum(1 for c in rck_checks
                if c.get("ok") and c.get("verifiable", True)),
            len(rck_checks)) if rck_checks else None,
        "substantive": [c["name"] for c in substantive],
        "diagnosis": rck.get("_diagnosis") or {},
        "ref_supplied": rck.get("_advisor_reference_supplied_at_recheck"),
    }


def _fmt(v, spec: str = "", dash: str = "—") -> str:
    if v is None:
        return dash
    try:
        return format(v, spec) if spec else str(v)
    except (TypeError, ValueError):
        return str(v)


def render(rows: list[dict]) -> str:
    out: list[str] = []
    w = out.append

    w("# Index of `results/`\n")
    w("Generated by `scripts/results_index.py` from each run's own artifacts. "
      "Do not edit by hand.\n")
    w("`validity then` is the run's verdict under the rules in force when it "
      "was made. `validity now` is `scripts/recheck_runs.py` re-judging it "
      "under the current, stricter rules. Where those differ, the difference "
      "is the point — the numbers were not re-measured, the standard moved.\n")

    healthy = [r for r in rows if not r["substantive"]]
    # A run that fails is not automatically a broken run, and the distinction
    # is the same one the failure taxonomy makes elsewhere in this project.
    # A pre-fix artifact failed because the harness got better. A rejected arm
    # failed because the treatment was worse. Filing them together would bury
    # the only rejection this project actually made.
    superseded = [r for r in rows if r["substantive"]
                  and all(r["diagnosis"].get(n) for n in r["substantive"])]
    rejected = [r for r in rows if r["substantive"] and r not in superseded]

    w("\n## Runs behind published numbers\n")
    w("| run | stage | n | C | wall s | fail | $/query | q/s | ticker | topics | "
      "validity then | now |")
    w("|---|---|---|--:|--:|--:|--:|--:|--:|--:|:--:|:--:|")
    for r in sorted(healthy, key=lambda x: (str(x["stage"]), x["n"] or 0, x["c"] or 0)):
        vn = (f"{r['validity_now'][0]}/{r['validity_now'][1]}"
              if r["validity_now"] else "not re-judged")
        w(f"| `{r['dir']}` | {r['stage']} | {r['n']} | {r['c']} | "
          f"{_fmt(r['wall_s'], '.1f')} | {r['failures']} | "
          f"{_fmt(r['usd_per_query'], '.6f')} | {_fmt(r['q_per_s'], '.2f')} | "
          f"{_fmt(None if r['ticker_acc'] is None else 100*r['ticker_acc'], '.1f')} | "
          f"{_fmt(None if r['all_topics'] is None else 100*r['all_topics'], '.1f')} | "
          f"{r['validity_then'][0]}/{r['validity_then'][1]} | {vn} |")

    if rejected:
        w("\n## Rejected on measurement\n")
        w("The treatment was worse, and the harness says so. These are not "
          "mistakes — they are the reason the experiment was worth running, "
          "and an optimization that only ever produced acceptable arms would "
          "be an optimization with no gate behind it.\n")
        for r in sorted(rejected, key=lambda x: x["dir"]):
            w(f"\n**`{r['dir']}`** — {r['stage']}, n={r['n']}, C={r['c']}")
            for name in r["substantive"]:
                w(f"\n- `{name}`")
                why = r["diagnosis"].get(name)
                if why:
                    w(f"  <br>{why}")

    if superseded:
        w("\n## Superseded runs — kept, not deleted\n")
        w("These fail a check because the harness got stricter after they ran, "
          "not because the treatment was bad. They are kept because deleting "
          "the runs that fail your own gate is how a results directory becomes "
          "a highlight reel, and because each one is evidence that a guard now "
          "in place catches something that really happened.\n")
        for r in sorted(superseded, key=lambda x: x["dir"]):
            w(f"\n**`{r['dir']}`** — {r['stage']}, n={r['n']}, C={r['c']}")
            for name in r["substantive"]:
                w(f"\n- `{name}`")
                why = r["diagnosis"].get(name)
                if why:
                    w(f"  <br>{why}")

    supplied = [r for r in rows if r["ref_supplied"]]
    if supplied:
        w("\n## Advisor arms judged against a reference supplied at recheck\n")
        w("These arms were compared by hand when they ran, because the "
          "`--advisor-reference` flag did not exist yet. The comparison below "
          "is made by `validity.check_run` from briefing scores frozen at run "
          "time; only the *choice of reference* was supplied afterwards, and "
          "their manifests still record that they declared none.\n")
        for r in sorted(supplied, key=lambda x: x["dir"]):
            verdict = "REJECTED" if r["substantive"] else "passes its gates"
            w(f"- `{r['dir']}` vs `{r['ref_supplied']}` — **{verdict}**"
              + (f" ({', '.join(r['substantive'])})" if r["substantive"] else ""))

    w("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true",
                    help="write results/INDEX.md instead of printing")
    ap.add_argument("--results", default=RESULTS,
                    help="results directory (default: results/)")
    a = ap.parse_args()

    results_dir = a.results
    if not os.path.isdir(results_dir):
        print(f"no results directory at {results_dir}", file=sys.stderr)
        return 1

    rows = []
    for name in sorted(os.listdir(results_dir)):
        d = os.path.join(results_dir, name)
        if os.path.isdir(d):
            r = collect(d)
            if r:
                rows.append(r)

    if not rows:
        print("no runs found", file=sys.stderr)
        return 1

    text = render(rows)
    if a.write:
        p = os.path.join(results_dir, "INDEX.md")
        with open(p, "w", encoding="utf-8") as fh:
            fh.write(text)
        # Counted apart, because they mean opposite things: one is the harness
        # getting stricter, the other is a treatment being worse.
        n_sup = sum(1 for r in rows if r["substantive"]
                    and all(r["diagnosis"].get(n) for n in r["substantive"]))
        n_rej = sum(1 for r in rows if r["substantive"]) - n_sup
        print(f"wrote {os.path.relpath(p, ROOT)}  "
              f"({len(rows)} runs, {n_sup} superseded, {n_rej} rejected on "
              f"measurement)")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
